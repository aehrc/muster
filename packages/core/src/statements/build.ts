/**
 * What goes into a software statement, and when Muster refuses to make one.
 *
 * This module is the whole of the vouching decision, and it is pure on purpose. A
 * software statement is Muster telling a stranger's authorization server "register this
 * client, I vouch for the metadata" - so what the claim set says and who is allowed to
 * cause one to exist are the two most security-critical judgements in the codebase, and
 * both are decided here where they can be exhausted by unit tests with no database, no
 * network and no clock of their own (constitution principle II).
 *
 * Four decisions are worth stating.
 *
 * **The claim names come from the contract, not from convenience.**
 * `contracts/registration-profile.md` is a vendor-facing contract that Signet's
 * `002-trusted-dcr-tickets` implements against, so the claim vocabulary is centralised in
 * {@link buildSoftwareStatementClaims} and nowhere else. Renaming a claim is a breaking
 * change to somebody else's product.
 *
 * **The expiry is capped, not validated.** FR-023 requires an expiry no later than the
 * event's end plus the event's configured grace period, and the way to guarantee that is
 * to compute it rather than to check a number somebody supplied.
 * {@link vouchingExpirySeconds} derives it from the event alone, so there is no path by
 * which a longer one could be requested.
 *
 * **Refusal is the default.** {@link softwareStatementRefusal} answers "may this
 * statement exist?" by requiring every one of seven things to hold, in the order the
 * person can act on. A new reason to refuse is added here and is then enforced on every
 * route that mints, because there is only one place that decides.
 *
 * **The metadata is the pairing's snapshot.** Not the client's record as it stands now:
 * the snapshot is what the two parties negotiated (`data-model.md`), and an entry edited
 * after the request must not silently change what Muster vouches for.
 *
 * Author: John Grimes
 */

